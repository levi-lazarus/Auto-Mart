// Generates public/js/data.js from the server seed so the front end can run
// on static hosting (GitHub Pages / Netlify) when the API is not available.
const fs = require('fs');
const path = require('path');
const cars = require('../server/data/cars');

const out = path.join(__dirname, '..', 'public', 'js', 'data.js');
fs.writeFileSync(out, `// AUTO-GENERATED by scripts/build-data.js — do not edit by hand.\nexport const CARS = ${JSON.stringify(cars, null, 2)};\n`);
console.log(`Wrote ${cars.length} cars to ${path.relative(process.cwd(), out)}`);
